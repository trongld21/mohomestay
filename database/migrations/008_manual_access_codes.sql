CREATE TABLE IF NOT EXISTS manual_access_codes (
    id CHAR(32) PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    lock_id BIGINT UNSIGNED NOT NULL,
    code VARCHAR(9) NULL,
    remote_id BIGINT UNSIGNED NULL,
    starts_at DATETIME NOT NULL,
    ends_at DATETIME NOT NULL,
    sync_status ENUM('PENDING','UNKNOWN','READY','FAILED') NOT NULL DEFAULT 'PENDING',
    sync_error VARCHAR(500) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
